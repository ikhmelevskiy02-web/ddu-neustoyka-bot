"""
Оформление уже посчитанного результата в дружелюбный текст.

Модель получает готовые цифры и явную инструкцию не менять их — она отвечает
только за формулировки, а не за арифметику.
"""
from __future__ import annotations

from llm.groq_client import GroqClient

_SYSTEM_PROMPT = """\
Ты — ассистент, который дружелюбно и по-русски объясняет пользователю результат \
расчёта неустойки по ДДУ. Тебе дан JSON с уже посчитанными цифрами. Твоя задача — \
кратко (4-6 предложений) объяснить результат простым языком, БЕЗ изменения хотя бы \
одной цифры из вводных данных. Не пересчитывай и не округляй по-своему. Не добавляй \
предупреждений, которых нет в списке warnings — просто перескажи их своими словами. \
Не используй markdown-заголовки. Пиши как живой человек, а не как юридический документ.
"""


def generate_explanation(client: GroqClient, result_json: str) -> str | None:
    return client.complete_text(_SYSTEM_PROMPT, result_json)
