"""
Штраф за неудовлетворение требований участника долевого строительства в
добровольном порядке — ч. 3 ст. 10 Федерального закона № 214-ФЗ.

См. раздел 4 docs/LEGAL_SPEC.md. Коротко:
- с 01.09.2024 штраф составляет 5% от присуждённой суммы (раньше — 50% по ст. 13
  Закона о защите прав потребителей);
- начисление штрафа "заморожено" на период 01.01.2025–31.12.2025 Постановлением
  Правительства РФ № 326;
- Постановление КС РФ от 14.04.2026 № 24-П уточнило порядок применения
  переходных правил для требований, возникших до 01.09.2024, — эта зона требует
  проверки юристом, поэтому модуль не пытается автоматически выбрать между
  5% и 50%, а только предупреждает.
"""
from __future__ import annotations

from datetime import date

from domain.models import ShtrafResult
from domain.moratorium import SHTRAF_MORATORIUM_END, SHTRAF_MORATORIUM_START, is_within

DEFAULT_SHTRAF_PERCENT = 5.0
PRE_REFORM_DATE = date(2024, 9, 1)


def calculate_shtraf(
    base_amount: float,
    voluntary_satisfaction_deadline: date | None = None,
    percent: float = DEFAULT_SHTRAF_PERCENT,
) -> ShtrafResult:
    """
    base_amount — сумма, присуждённая судом в пользу участника долевого строительства
        (неустойка + убытки + компенсация морального вреда; судебные расходы и сама
        госпошлина в базу штрафа НЕ включаются согласно устоявшейся практике).
    voluntary_satisfaction_deadline — дата, на которую истёк срок добровольного
        удовлетворения требований (обычно дата претензии + 10 дней по ст. 22 Закона
        о защите прав потребителей, либо иной срок, указанный в претензии). Используется
        только для предупреждений о зонах риска, не влияет на саму формулу.
    """
    warnings: list[str] = []

    if voluntary_satisfaction_deadline is not None:
        if is_within(voluntary_satisfaction_deadline, SHTRAF_MORATORIUM_START, SHTRAF_MORATORIUM_END):
            warnings.append(
                "Срок добровольного удовлетворения требований истёк в период "
                f"{SHTRAF_MORATORIUM_START.strftime('%d.%m.%Y')}–{SHTRAF_MORATORIUM_END.strftime('%d.%m.%Y')}, "
                "когда начисление штрафа по ч. 3 ст. 10 214-ФЗ было приостановлено "
                "Постановлением Правительства РФ № 326. Уточните у юриста, начисляется ли "
                "штраф в вашем случае."
            )
        if voluntary_satisfaction_deadline < PRE_REFORM_DATE:
            warnings.append(
                "Обязательство возникло до 01.09.2024, когда штраф ещё регулировался "
                "ст. 13 Закона о защите прав потребителей (50%), а не ч. 3 ст. 10 214-ФЗ (5%). "
                "Постановление КС РФ от 14.04.2026 № 24-П уточняет порядок применения "
                "переходных правил для таких случаев — обязательно проверьте актуальную практику "
                "или проконсультируйтесь с юристом, прежде чем использовать 5% для расчёта."
            )

    amount = round(base_amount * percent / 100, 2)

    warnings.append(
        "В базу для штрафа обычно включают неустойку, убытки и компенсацию морального вреда, "
        "но не судебные расходы и не саму госпошлину — проверьте состав базы перед подачей иска."
    )

    return ShtrafResult(base_amount=base_amount, percent=percent, amount=amount, warnings=warnings)
